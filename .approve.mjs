import { chromium } from "@playwright/test";
const [,, jobId, SP] = process.argv;
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://localhost:3000/login");
await page.fill('input[name="email"]', "admin@demo.sewersquad.test");
await page.fill('input[name="password"]', "SewerSquad-demo-2026");
await page.click('button[type="submit"]');
await page.waitForURL("**/admin/dashboard");
await page.goto(`http://localhost:3000/admin/jobs/${jobId}`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${SP}/review.png`, fullPage: true });
await page.getByRole("button", { name: "Approve & finalize" }).first().click();
await page.getByRole("dialog").getByRole("button", { name: "Approve & finalize" }).click();
await page.getByText(/Approved\./).first().waitFor({ timeout: 60000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${SP}/approved.png`, fullPage: true });
console.log("errors", JSON.stringify(errors));
await browser.close();
