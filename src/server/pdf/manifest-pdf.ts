import "server-only";
import type { Db } from "../db";
import { storage } from "../storage";
import { PdfWriter, colors, pdfSafe } from "./layout";
import type { ManifestData } from "../services/manifests";
import { formatDateKey, formatInstant } from "@/lib/dates";
import { companyTimeZone, getSetting } from "../services/settings";

/** Render a manifest version (immutable snapshot) to PDF. */
export async function renderManifestPdf(db: Db, manifestId: string, version: number): Promise<Uint8Array> {
  const v = await db.manifestVersion.findUniqueOrThrow({ where: { manifestId_version: { manifestId, version } }, include: { manifest: { include: { signatures: true } } } });
  const data = v.data as unknown as ManifestData;
  const tz = await companyTimeZone(db);
  const company = await getSetting("company", db);
  const fmt = (iso: string | null) => (iso ? formatInstant(iso, tz) : null);

  const w = await PdfWriter.create(`Manifest ${data.reference.manifestNumber}`, `Manifest ${data.reference.manifestNumber} · Version ${v.version} · Integrity ${v.contentHash.slice(0, 16)} · Generated by ${company.name}`);
  w.header("Waste Manifest", data.template ? `${data.template.name} · ${data.template.jurisdiction}` : "Non-hazardous liquid waste", [
    data.reference.manifestNumber,
    `Service date ${formatDateKey(data.reference.serviceDate, "long")}`,
    `Job ${data.reference.jobNumber}`,
    `Version ${v.version}${v.isFinal ? " · Finalized" : " · DRAFT"}`,
  ]);
  if (!v.isFinal) w.stamp("DRAFT - NOT FINALIZED");

  w.section("Generator", "Source: customer account records");
  w.fields([
    ["Business / generator", data.generator.businessName],
    ["Customer", `${data.generator.organizationName} (${data.generator.accountNumber})`],
    ["Service address", data.generator.address],
    ["County", data.generator.county],
    ["Site contact", data.generator.contactName],
    ["Contact phone", data.generator.contactPhone],
  ]);

  w.section("Collection", "Source: driver-entered field data");
  w.fields([
    ["Waste type", data.collection.wasteType],
    ["Total gallons collected", `${data.collection.totalGallons.toLocaleString()} gal`],
    ["Service start", fmt(data.collection.startedAt)],
    ["Service completed", fmt(data.collection.finishedAt)],
  ]);
  if (data.collection.equipment.length) {
    w.table(
      ["Asset", "Equipment", "Capacity", "Gallons pumped", "Service performed"],
      data.collection.equipment.map((e) => [e.assetTag, e.type, `${e.capacityGallons.toLocaleString()} gal`, `${e.gallonsPumped.toLocaleString()} gal`, e.servicePerformed ?? ""]),
      [1.2, 1.6, 1, 1.1, 2],
      ["left", "left", "right", "right", "left"],
    );
  }
  if (data.collection.notes) w.text(`Driver notes: ${data.collection.notes}`, { size: 8.5, color: colors.muted, gap: 4 });

  w.section("Hauler / transporter", "Source: company & fleet records");
  w.fields([
    ["Hauler", data.hauler.name],
    ["Transporter permit / license", data.hauler.transporterPermitNumber],
    ["Registration", data.hauler.registrationNumber],
    ["Driver", data.hauler.driverName],
    ["Truck / unit", data.hauler.truckUnit],
    ["VIN", data.hauler.vin],
    ["License plate", data.hauler.licensePlate],
    ["Vehicle permit", data.hauler.vehiclePermit],
  ]);

  w.section("Disposal", "Source: documented disposal records");
  w.fields([
    ["Disposal facility", data.disposal.facilityName],
    ["Facility address", data.disposal.facilityAddress],
    ["Facility permit", data.disposal.facilityPermit],
    ["Disposal date / time", fmt(data.disposal.disposedAt)],
    ["Ticket / reference", data.disposal.ticketNumber],
    ["Facility acknowledgment", data.disposal.facilityAcknowledged ? "Recorded on disposal ticket" : "Not recorded"],
  ]);

  if (Object.keys(data.extra).length) {
    w.section("Additional regulatory fields", "Source: administrator");
    w.fields(Object.entries(data.extra));
  }

  w.section("Signatures & certifications");
  const sigs = v.manifest.signatures;
  const blocks: { title: string; name: string | null; detail: string; docId: string | null }[] = [];
  const c = data.signatures.customer;
  const custSig = sigs.filter((s) => s.role === "CUSTOMER").sort((a, b) => b.signedAt.getTime() - a.signedAt.getTime())[0];
  blocks.push({
    title: "Customer acknowledgment",
    name: c?.unavailable ? "Representative unavailable" : c?.name ?? null,
    detail: c?.unavailable ? `Reason recorded by driver: ${c.unavailableReason ?? "—"}` : [c?.title, fmt(c?.signedAt ?? null)].filter(Boolean).join(" · "),
    docId: c?.unavailable ? null : custSig?.signatureDocumentId ?? null,
  });
  const drvSig = sigs.filter((s) => s.role === "DRIVER").sort((a, b) => b.signedAt.getTime() - a.signedAt.getTime())[0];
  blocks.push({ title: "Driver / hauler certification", name: data.signatures.driver?.name ?? null, detail: fmt(data.signatures.driver?.signedAt ?? null) ?? "", docId: drvSig?.signatureDocumentId ?? null });

  w.ensure(110);
  const colW = w.width / 2;
  const top = w.y;
  for (const [i, b] of blocks.entries()) {
    const x = w.left + i * colW;
    w.y = top;
    w.page.drawText(pdfSafe(b.title), { x, y: w.y - 8, size: 7.5, font: w.font, color: colors.muted });
    w.y -= 14;
    if (b.docId) {
      const ver = await db.documentVersion.findFirst({ where: { documentId: b.docId }, orderBy: { version: "desc" } });
      if (ver) {
        try {
          await w.image(await storage().get(ver.storageKey), x, colW - 30, 48);
        } catch {
          /* missing image: leave the box empty rather than fabricate */
        }
      }
    }
    w.page.drawLine({ start: { x, y: top - 66 }, end: { x: x + colW - 30, y: top - 66 }, thickness: 0.5, color: colors.border });
    w.page.drawText(pdfSafe(b.name ?? "Not signed"), { x, y: top - 78, size: 9.5, font: w.bold, color: b.name ? colors.text : colors.muted });
    w.page.drawText(pdfSafe(b.detail.slice(0, 80)), { x, y: top - 90, size: 7.5, font: w.font, color: colors.muted });
  }
  w.y = top - 104;
  if (data.hauler.certificationStatement) w.text(data.hauler.certificationStatement, { size: 7.5, color: colors.muted, gap: 4 });

  w.section("Administrator verification", "Source: Sewer Squad office");
  w.fields([
    ["Verified by", data.verification.verifiedBy],
    ["Verified at", fmt(data.verification.verifiedAt)],
    ["Version note", v.reason],
    ["Integrity hash (SHA-256)", v.contentHash.slice(0, 32)],
  ]);
  w.text("This document reflects records captured in the Sewer Squad platform. It is not a substitute for any jurisdiction-specific form or certification unless that agency has accepted it. Official third-party manifests, where required, are attached separately.", { size: 7, color: colors.muted });
  return w.save();
}
